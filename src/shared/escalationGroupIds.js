/**
 * The id for a group name, or null when this account has no such group.
 *
 * Null is the honest answer and callers must treat it as one: tag the ticket
 * and say assignment was skipped. Guessing an id would assign real work to the
 * wrong queue, which is worse than leaving it unassigned and saying so.
 *
 * @param {string|null|undefined} name
 * @returns {number|null}
 */
export function groupIdFor(name) {
  if (typeof name !== "string" || !name) return null;
  const id = ESCALATION_GROUP_IDS[name];
  return typeof id === "number" && Number.isInteger(id) && id > 0 ? id : null;
}
